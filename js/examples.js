// كل مثال: اتجاه سابق (down/up/none) + شموع النمط

const k = (o, h, l, c) => ({ o, h, l, c, v: 1000 });

export function prefix(trend, n = 10) {
  const out = [];
  for (let i = 0; i < n; i++) {
    if (trend === 'down') { const o = 120 - 2 * i; out.push(k(o, o + 0.5, o - 2.5, o - 2)); }
    else if (trend === 'up') { const o = 80 + 2 * i; out.push(k(o, o + 2.5, o - 0.5, o + 2)); }
    else { const o = 100 + (i % 2 ? 0.6 : -0.6); out.push(k(o, o + 1.4, o - 1.4, o + (i % 2 ? -1 : 1))); }
  }
  return out;
}

